/**
 * Returns a list of words filtered by maximum length.
 * If maxLength is 99 or >= max word length, returns all words.
 */
export function getWordsByMaxLength(maxLength: number): string[] {
  if (maxLength >= 99) return ASL_WORDS;
  return ASL_WORDS.filter((w) => w.length <= maxLength);
}

/**
 * Returns a list of words filtered by exact length.
 */
export function getWordsByExactLength(length: number): string[] {
  return ASL_WORDS.filter((w) => w.length === length);
}

/**
 * Pick a random word from the word list given a max length constraint.
 */
export function getRandomFingerspellingWord(maxLength: number, excludeWords: string[] = []): string {
  const pool = getWordsByMaxLength(maxLength);
  const available = pool.filter((w) => !excludeWords.includes(w));
  const targetPool = available.length > 0 ? available : pool;
  const randomIndex = Math.floor(Math.random() * targetPool.length);
  return targetPool[randomIndex] || "asl";
}
